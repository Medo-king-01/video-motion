def to_svg(icon: dict) -> str:
    draw, stagger, hz = icon["anim"]["draw"], icon["anim"]["stagger"], icon["anim"]["pulse_hz"]
    body = []
    for i, part in enumerate(icon["parts"]):
        delay = round(i * stagger, 3)
        m = f' transform="matrix({",".join(f"{v:g}" for v in part["m"])})"' if part.get("m") else ""
        if part["k"] == "p":
            cls = "f" if part.get("fill") else "a"
            extra = "" if part.get("fill") else ' pathLength="1"'
            body.append(f'  <path class="{cls}"{extra} d="{part["d"]}"{m} style="animation-delay:{delay}s"/>')
        elif part["k"] == "s":
            pts = " ".join(f"{p[0]:g},{p[1]:g}" for p in part["pts"])
            if part.get("fill"):
                body.append(f'  <polygon class="f" points="{pts}" style="animation-delay:{delay}s"/>')
            else:
                tag = "polygon" if part["closed"] else "polyline"
                body.append(f'  <{tag} class="a" pathLength="1" points="{pts}" style="animation-delay:{delay}s"/>')
        elif part["k"] == "d":
            body.append(f'  <circle class="d" cx="{part["c"][0]:g}" cy="{part["c"][1]:g}" r="{part["r"]:g}" '
                        f'style="animation-delay:{delay}s,{delay + 0.35}s"/>')
        else:
            body.append(f'  <rect class="f" x="{part["x"]:g}" y="{part["y"]:g}" width="{part["w"]:g}" '
                        f'height="{part["h"]:g}" rx="{part["r"]:g}" style="animation-delay:{delay}s"/>')
    style = SVG_STYLE % {"sw": f'{icon["stroke"]:g}', "dur": f"{draw}s", "period": f"{round(1 / hz, 2)}s"}
    title = f"{icon['en']} — {icon['ar']}" if icon["ar"] else icon["en"]
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {icon["grid"]:g} {icon["grid"]:g}" '
            f'width="96" height="96" role="img" aria-label="{title}" data-icon="{icon["id"]}">\n'
            f'  <title>{title}</title>\n' + style + "\n" + "\n".join(body) + "\n</svg>\n")


