def _arc_points(x0: float, y0: float, rx: float, ry: float, rot: float, large: int, sweep: int,
                x1: float, y1: float, steps: int = 16) -> list[list[float]]:
    """Endpoint → centre parameterisation, then sample (SVG spec appendix F)."""
    if rx == 0 or ry == 0:
        return [[x1, y1]]
    rx, ry = abs(rx), abs(ry)
    phi = math.radians(rot)
    cp, sp = math.cos(phi), math.sin(phi)
    dx, dy = (x0 - x1) / 2, (y0 - y1) / 2
    x1p, y1p = cp * dx + sp * dy, -sp * dx + cp * dy
    lam = (x1p ** 2) / (rx ** 2) + (y1p ** 2) / (ry ** 2)
    if lam > 1:
        rx, ry = rx * math.sqrt(lam), ry * math.sqrt(lam)
    num = rx ** 2 * ry ** 2 - rx ** 2 * y1p ** 2 - ry ** 2 * x1p ** 2
    den = rx ** 2 * y1p ** 2 + ry ** 2 * x1p ** 2
    coef = math.sqrt(max(0.0, num / den)) if den else 0.0
    if large == sweep:
        coef = -coef
    cxp, cyp = coef * rx * y1p / ry, -coef * ry * x1p / rx
    cx = cp * cxp - sp * cyp + (x0 + x1) / 2
    cy = sp * cxp + cp * cyp + (y0 + y1) / 2

    def ang(ux, uy, vx, vy):
        return math.atan2(ux * vy - uy * vx, ux * vx + uy * vy)

    t1 = ang(1, 0, (x1p - cxp) / rx, (y1p - cyp) / ry)
    dt = ang((x1p - cxp) / rx, (y1p - cyp) / ry, (-x1p - cxp) / rx, (-y1p - cyp) / ry)
    if not sweep and dt > 0:
        dt -= 2 * math.pi
    elif sweep and dt < 0:
        dt += 2 * math.pi
    return [[round(cx + rx * math.cos(t1 + dt * i / steps) * cp - ry * math.sin(t1 + dt * i / steps) * sp, 3),
             round(cy + rx * math.cos(t1 + dt * i / steps) * sp + ry * math.sin(t1 + dt * i / steps) * cp, 3)]
            for i in range(1, steps + 1)]


def flatten_path(d: str, steps: int = 14) -> list[list[list[float]]]:
    """Flatten an SVG path to a list of polylines (one per subpath)."""
    r = _PathReader(d)
    x = y = sx = sy = 0.0
    prev_c: tuple[float, float] | None = None
    prev_q: tuple[float, float] | None = None
    subs: list[list[list[float]]] = []
    cur: list[list[float]] = []
    cmd: str | None = None

    def curve(c1, c2, ex, ey):
        for s in range(1, steps + 1):
            t = s / steps
            mt = 1 - t
            cur.append([round(mt ** 3 * x + 3 * mt ** 2 * t * c1[0] + 3 * mt * t ** 2 * c2[0] + t ** 3 * ex, 3),
                        round(mt ** 3 * y + 3 * mt ** 2 * t * c1[1] + 3 * mt * t ** 2 * c2[1] + t ** 3 * ey, 3)])

    while not r.eof():
        mark = r.i
        c = r.cmd()
        if c:
            cmd = c
        elif cmd is None:
            break
        if cmd is None:
            break
        up, rel = cmd.upper(), cmd.islower()
        ox, oy = (x, y) if rel else (0.0, 0.0)
        if up == "Z":
            if cur:
                cur.append([round(sx, 3), round(sy, 3)])
                subs.append(cur)
                cur = []
            x, y = sx, sy
            cmd = None
            continue
        if up == "M":
            if cur:
                subs.append(cur)
            x, y = ox + r.num(), oy + r.num()
            sx, sy = x, y
            cur = [[round(x, 3), round(y, 3)]]
            cmd = "l" if rel else "L"
        elif up == "L":
            x, y = ox + r.num(), oy + r.num()
            cur.append([round(x, 3), round(y, 3)])
        elif up == "H":
            x = ox + r.num()
            cur.append([round(x, 3), round(y, 3)])
        elif up == "V":
            y = oy + r.num()
            cur.append([round(x, 3), round(y, 3)])
        elif up == "C":
            c1 = (ox + r.num(), oy + r.num())
            c2 = (ox + r.num(), oy + r.num())
            ex, ey = ox + r.num(), oy + r.num()
            curve(c1, c2, ex, ey)
            prev_c, prev_q = c2, None
            x, y = ex, ey
        elif up in ("S", "Q", "T"):
            if up == "S":
                c1 = (2 * x - prev_c[0], 2 * y - prev_c[1]) if prev_c else (x, y)
                c2 = (ox + r.num(), oy + r.num())
                ex, ey = ox + r.num(), oy + r.num()
            elif up == "Q":
                q = (ox + r.num(), oy + r.num())
                ex, ey = ox + r.num(), oy + r.num()
                c1 = (x + (q[0] - x) * 2 / 3, y + (q[1] - y) * 2 / 3)
                c2 = (q[0] + (ex - q[0]) * 1 / 3, q[1] + (ey - q[1]) * 1 / 3)
                prev_q = q
            else:
                q = (2 * x - prev_q[0], 2 * y - prev_q[1]) if prev_q else (x, y)
                ex, ey = ox + r.num(), oy + r.num()
                c1 = (x + (q[0] - x) * 2 / 3, y + (q[1] - y) * 2 / 3)
                c2 = (q[0] + (ex - q[0]) * 1 / 3, q[1] + (ey - q[1]) * 1 / 3)
                prev_q = q
            curve(c1, c2, ex, ey)
            prev_c = c2 if up == "S" else None
            x, y = ex, ey
        elif up == "A":
            rx, ry, rot = r.num(), r.num(), r.num()
            large, sweep = r.flag(), r.flag()
            ex, ey = ox + r.num(), oy + r.num()
            cur += _arc_points(x, y, rx, ry, rot, large, sweep, ex, ey)
            x, y = ex, ey
        else:  # an unexpected letter: stop instead of spinning on it
            break
        if r.i == mark and cmd not in (None,):
            break
    if cur:
        subs.append(cur)
    return [s for s in subs if len(s) >= 2]


# --------------------------------------------------------------------------- primitives
def _arc(cx: float, cy: float, r: float, a0: float, a1: float, n: int = 24) -> list[list[float]]:
    return [[round(cx + r * math.cos(math.radians(a0 + (a1 - a0) * i / (n - 1))), 3),
             round(cy + r * math.sin(math.radians(a0 + (a1 - a0) * i / (n - 1))), 3)] for i in range(n)]


def _circle(cx: float, cy: float, r: float, n: int = 56) -> list[list[float]]:
    return [[round(cx + r * math.cos(2 * math.pi * i / n), 3), round(cy + r * math.sin(2 * math.pi * i / n), 3)]
            for i in range(n)]


def _round_rect(x: float, y: float, w: float, h: float, r: float) -> list[list[float]]:
    r = max(0.0, min(r, w / 2, h / 2))
    pts: list[list[float]] = []
    for cx, cy, a0 in ((x + w - r, y + r, -90), (x + w - r, y + h - r, 0),
                       (x + r, y + h - r, 90), (x + r, y + r, 180)):
        pts += _arc(cx, cy, r, a0, a0 + 90, 5) if r else [[round(cx, 3), round(cy, 3)]]
    return pts


def _poly_len(pts: list[list[float]]) -> float:
    return sum(math.dist(pts[i], pts[i - 1]) for i in range(1, len(pts)))


def _apply(m: list[float], pts: list[list[float]]) -> list[list[float]]:
    a, b, c, d, e, f = m
    return [[round(a * x + c * y + e, 3), round(b * x + d * y + f, 3)] for x, y in pts]


def _expand(shape: dict) -> dict:
    """Turn one registry primitive into a part the painters understand."""
    kind = shape["t"]
    filled = bool(shape.get("fill"))
    if kind == "path":
        subs = flatten_path(shape["d"])
        if not subs:
            return {}
        m = shape.get("m")
        if m:
            subs = [_apply(m, s) for s in subs]
        part = {"k": "p", "d": shape["d"], "subs": subs, "fill": filled,
                "len": round(sum(_poly_len(sub) for sub in subs), 2)}
        if m:
            part["m"] = m
        return part
    if kind == "line":
        pts, closed = [list(map(float, p)) for p in shape["p"]], False
    elif kind == "poly":
        pts, closed = [list(map(float, p)) for p in shape["p"]], bool(shape.get("closed"))
    elif kind == "rect":
        pts, closed = _round_rect(shape["x"], shape["y"], shape["w"], shape["h"], shape.get("r", 0)), True
    elif kind == "circle":
        pts, closed = _circle(shape["c"][0], shape["c"][1], shape["r"]), True
    elif kind == "ellipse":
        pts = [[round(shape["c"][0] + shape["rx"] * math.cos(2 * math.pi * i / 56), 3),
                round(shape["c"][1] + shape["ry"] * math.sin(2 * math.pi * i / 56), 3)] for i in range(56)]
        closed = True
    elif kind == "arc":
        pts, closed = _arc(shape["c"][0], shape["c"][1], shape["r"], shape["a"][0], shape["a"][1]), False
    elif kind == "dot":
        return {"k": "d", "c": list(map(float, shape["c"])), "r": float(shape["r"])}
    elif kind == "fillrect":
        return {"k": "f", "x": shape["x"], "y": shape["y"], "w": shape["w"], "h": shape["h"], "r": shape.get("r", 0)}
    else:
        raise SystemExit(f"unknown primitive {kind!r}")
    m = shape.get("m")
    if m:
        pts = _apply(m, pts)
    part = {"k": "s", "pts": pts, "closed": closed}
    if filled:
        part["fill"] = True
    return part


def _icon(icon: dict, source: str) -> dict:
    if not icon.get("id"):
        raise SystemExit("icon without id")
    parts = [p for p in (_expand(s) for s in icon["shapes"]) if p]
    if not parts:
        raise SystemExit(f"{icon['id']}: no geometry after expansion")
    return {
        "id": icon["id"],
        "ar": icon.get("ar") or "",
        "en": icon.get("en") or icon["id"],
        "group": icon.get("group", "misc"),
        "source": source,
        "grid": icon.get("grid", 24),
        "stroke": icon.get("stroke", 2),
        "anim": {"draw": icon["anim"]["draw"], "stagger": icon["anim"]["stagger"],
                 "pulse_hz": icon["anim"].get("pulse_hz", 1.2)},
        "parts": parts,
    }


def build_model() -> list[dict]:
    model, seen = [], set()
    house = json.loads(HOUSE.read_text(encoding="utf-8"))
    imported = json.loads(IMPORTED.read_text(encoding="utf-8")) if IMPORTED.is_file() else {"icons": []}
    for icon in house["icons"]:
        if icon["id"] in seen:
            raise SystemExit(f"duplicate icon id {icon['id']}")
        seen.add(icon["id"])
        if not icon.get("ar"):
            raise SystemExit(f"{icon['id']}: every house icon needs an Arabic label for the reels")
        model.append(_icon(icon, "house"))
    for icon in imported["icons"]:
        if icon["id"] in seen:
            continue  # a promoted copy lives in the house registry
        seen.add(icon["id"])
        model.append(_icon(icon, "itshover"))
    return model


