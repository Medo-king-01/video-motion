def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = ap.parse_args()
    files = artefacts()
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check:
        for path in stale[:20]:
            print("STALE", path.relative_to(SKILL))
        print("icons:", "in sync" if not stale else f"{len(stale)} stale file(s)")
        return 1 if stale else 0
    groups: dict[str, int] = {}
    for icon in json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))["icons"]:
        groups[icon["group"]] = groups.get(icon["group"], 0) + 1
    print(f"icons: wrote {len(files)} files — " + " · ".join(f"{k}:{v}" for k, v in sorted(groups.items())))
    return 0


