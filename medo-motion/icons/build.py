class _PathReader:
    """Cursor-based SVG path reader. Arc flags are single digits and may touch the next number."""

    def __init__(self, d: str):
        self.d, self.i = d, 0

    def skip(self) -> None:
        while self.i < len(self.d) and self.d[self.i] in " \t\r\n,":
            self.i += 1

    def eof(self) -> bool:
        self.skip()
        return self.i >= len(self.d)

    def cmd(self) -> str | None:
        self.skip()
        if self.i < len(self.d) and self.d[self.i].isalpha():
            c = self.d[self.i]
            self.i += 1
            return c
        return None

    def num(self) -> float:
        self.skip()
        start = self.i
        if self.i < len(self.d) and self.d[self.i] in "+-":
            self.i += 1
        while self.i < len(self.d) and self.d[self.i].isdigit():
            self.i += 1
        if self.i < len(self.d) and self.d[self.i] == ".":
            self.i += 1
            while self.i < len(self.d) and self.d[self.i].isdigit():
                self.i += 1
        if self.i < len(self.d) and self.d[self.i] in "eE":
            self.i += 1
            if self.i < len(self.d) and self.d[self.i] in "+-":
                self.i += 1
            while self.i < len(self.d) and self.d[self.i].isdigit():
                self.i += 1
        return float(self.d[start:self.i]) if self.i > start else 0.0

    def flag(self) -> int:
        self.skip()
        v = 1 if self.i < len(self.d) and self.d[self.i] == "1" else 0
        self.i += 1
        return v


