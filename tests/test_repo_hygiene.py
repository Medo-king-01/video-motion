"""Repository hygiene that Git itself must enforce: binary assets and line endings.

There is no Git LFS here on purpose (see `.gitattributes`), so the attribute file is the only
thing standing between a binary font and a textconv/EOL rewrite. These assertions are cheap and
they fail the moment someone deletes the file or narrows it while "cleaning up".
"""
from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
ATTRIBUTES = ROOT / ".gitattributes"


def check_attr(attribute: str, path: str) -> str:
    result = subprocess.run(["git", "check-attr", attribute, "--", path], cwd=str(ROOT),
                            capture_output=True, text=True, check=True)
    return result.stdout.strip().rsplit(": ", 1)[-1]


def test_gitattributes_exists_and_declares_auto_text() -> None:
    assert ATTRIBUTES.is_file()
    text = ATTRIBUTES.read_text(encoding="utf-8")
    assert "* text=auto" in text
    assert "filter=lfs" not in text  # LFS is a deliberate non-decision, not an accident


@pytest.mark.parametrize("path", [
    "assets/fonts/Cairo/Cairo_800ExtraBold.ttf",
    "assets/poses/source/5be9f266.png",
    "docs/audition/01-six-presets.mp3",
])
def test_assets_are_marked_binary(path: str) -> None:
    assert check_attr("binary", path) == "set"


@pytest.mark.parametrize("path", [
    "tools/doctor.py",
    "AGENTS.md",
    "medo-motion/motion/transitions.json",
])
def test_text_files_are_pinned_to_lf(path: str) -> None:
    assert check_attr("text", path) == "set"
    assert check_attr("eol", path) == "lf"


def test_the_generated_ffprobe_shim_works_from_any_directory(tmp_path: Path) -> None:
    """`tools/bin/ffprobe` is called by tools whose cwd is a project, not the repo root.

    A shim that `exec`s a relative `.venv/bin/python` dies with "not found" the moment the caller
    is not standing in the repository — which is exactly how the hybrid renderer runs.
    """
    shim = ROOT / "tools" / "bin" / "ffprobe"
    if not shim.is_file():
        pytest.skip("tools/bin/ffprobe is generated by tools/setup.sh")
    media = tmp_path / "probe.mp4"
    subprocess.run(["ffmpeg", "-v", "error", "-f", "lavfi", "-i", "color=c=black:s=64x64:r=30",
                    "-frames:v", "6", "-pix_fmt", "yuv420p", str(media)],
                   check=True, capture_output=True)
    result = subprocess.run([str(shim), "-v", "error", "-show_entries", "stream=width",
                             "-of", "csv=p=0", str(media)], cwd=str(tmp_path),
                            capture_output=True, text=True)
    assert result.returncode == 0, result.stderr
    assert '"width": 64' in result.stdout  # the shim answers in JSON from any cwd


def test_setup_writes_an_absolute_interpreter_into_the_ffprobe_shim() -> None:
    source = (ROOT / "tools" / "setup.sh").read_text(encoding="utf-8")
    assert 'PY_ABS=$(cd "$(dirname "$(command -v "$PY")")" && pwd)' in source
    assert '$(command -v "$PY")" "$ROOT/tools/ffprobe_shim.py"' not in source
