#!/usr/bin/env python3
"""Canvas for engines K and R (B7د): one profile document, two honest render paths.

Engines K and R are laid out in the brand's 1080×1920 design space. A project may therefore ask for a
*device downscale* of that space — `draft-15` gives 540×960 at 0.5 — and engine K takes it as `--scale`
while engine R takes it as a generated `src/canvas.ts` plus the scaled stage in `Root.tsx`. Another aspect
ratio, or anything larger than the design space, is refused by name: those layouts would have to be
re-authored, and pretending the same scene code survives a reshape is the lie this tool exists to prevent.

    python3 tools/canvas_engines.py resolve out/canvas.json --engine k
    python3 tools/canvas_engines.py apply out/canvas.json          # writes the Remotion canvas.ts
    python3 tools/canvas_engines.py check                          # is src/canvas.ts a legal canvas?

Exit codes: 0 ok · 1 canvas refused (X-codes) · 2 unreadable file.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "medo-motion" / "brand" / "brand.json"
REMOTION_SRC = ROOT / "medo-motion" / "templates" / "remotion" / "src"
CANVAS_FILE = REMOTION_SRC / "canvas.ts"


class CanvasError(ValueError):
    def __init__(self, code: str, message: str):
        self.code = code
        self.message = message
        super().__init__(f"{code} {message}")


def design() -> dict:
    brand = json.loads(BRAND.read_text(encoding="utf-8"))
    canvas = brand["canvas"]
    return {"width": canvas["w"], "height": canvas["h"], "fps": canvas["fps"]}


def resolve(document: dict, *, env: str = "canvas") -> dict:
    """Validate a `profiles.py canvas` document against the design space and describe both paths."""
    base = design()
    if not isinstance(document, dict):
        raise CanvasError("X01", f"{env}: the canvas document must be an object")
    width, height, fps = document.get("w"), document.get("h"), document.get("fps")
    for name, value in (("w", width), ("h", height), ("fps", fps)):
        if isinstance(value, bool) or not isinstance(value, int) or value <= 0:
            raise CanvasError("X01", f"{env}: {name} must be a positive integer")
    if width * base["height"] != height * base["width"]:
        raise CanvasError("X02", f"{env}: {width}×{height} is not a uniform scale of "
                                   f"{base['width']}×{base['height']} — engines K and R own one 9:16 design "
                                   "space; a reshape needs new layouts, not a scaled buffer")
    if width > base["width"] or height > base["height"]:
        raise CanvasError("X03", f"{env}: {width}×{height} is larger than the "
                                   f"{base['width']}×{base['height']} design space")
    if width % 2 or height % 2:
        raise CanvasError("X04", f"{env}: {width}×{height} must be even for H.264 4:2:0 output")
    scale = width / base["width"]
    device = (width, height)
    return {
        "profile": document.get("profile") or "brand",
        "design": (base["width"], base["height"]),
        "device": device,
        "scale": scale,
        "fps": fps,
        "k": [] if scale == 1 else ["--scale", f"{scale:g}"],
        "r": {"width": width, "height": height, "scale": scale, "fps": fps},
    }


def k_args(document: dict) -> list[str]:
    """Engine K already owns a device buffer: its canvas is `--scale` of the design space."""
    return resolve(document, env="engine K").get("k") or []


def r_source(document: dict) -> str:
    """The `src/canvas.ts` engine R compiles: composition size, stage scale and rate in one place."""
    plan = resolve(document, env="engine R")
    width, height = plan["r"]["width"], plan["r"]["height"]
    return (
        "// Generated by tools/canvas_engines.py — engine R keeps the 1080×1920 design space and renders\n"
        f"// this uniform downscale of it (profile: {plan['profile']}).\n"
        "export const DESIGN = {width: 1080, height: 1920} as const;\n\n"
        f"export const CANVAS = {{width: {width}, height: {height}, scale: {plan['scale']!r}, "
        f"fps: {plan['fps']}}} as const;\n"
    )


def apply(document: dict, *, src: Path = REMOTION_SRC) -> Path:
    target = Path(src) / "canvas.ts"
    payload = r_source(document)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(payload, encoding="utf-8")
    return target


def check(path: Path = CANVAS_FILE) -> list[str]:
    """Read a generated canvas.ts back and hold it to the same rule; never trust the file blindly."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        return [f"X01 {path}: {exc}"]
    match = re.search(r"CANVAS\s*=\s*\{([^}]*)\}", text)
    if match is None:
        return [f"X01 {path}: CANVAS is missing"]
    values = {}
    for key in ("width", "height", "scale", "fps"):
        found = re.search(rf"{key}:\s*([-\d.]+)", match.group(1))
        if found is None:
            return [f"X01 {path}: CANVAS is missing {key}"]
        values[key] = float(found.group(1))
    if "DESIGN" not in text:
        return [f"X01 {path}: DESIGN is missing"]
    values["width"], values["height"], values["fps"] = int(values["width"]), int(values["height"]), int(values["fps"])
    try:
        resolve({"w": values["width"], "h": values["height"], "fps": values["fps"], "profile": "canvas.ts"})
    except CanvasError as exc:
        return [f"{exc.code} {path}: {exc.message}"]
    base = design()
    if abs(values["scale"] - values["width"] / base["width"]) > 1e-9:
        return [f"X04 {path}: CANVAS.scale does not match width ÷ {base['width']}"]
    return []


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    resolve_cmd = sub.add_parser("resolve", help="print what each engine needs for this canvas")
    resolve_cmd.add_argument("canvas", type=Path)
    resolve_cmd.add_argument("--engine", choices=("k", "r"), default=None)
    apply_cmd = sub.add_parser("apply", help="write engine R's src/canvas.ts")
    apply_cmd.add_argument("canvas", type=Path)
    apply_cmd.add_argument("--src", type=Path, default=REMOTION_SRC)
    check_cmd = sub.add_parser("check", help="verify a generated canvas.ts")
    check_cmd.add_argument("--file", type=Path, default=CANVAS_FILE)
    args = parser.parse_args(argv)

    if args.command == "check":
        errors = check(args.file)
        if errors:
            print("\n".join(errors), file=sys.stderr)
            return 1
        print(f"Valid canvas · {args.file}")
        return 0

    try:
        document = json.loads(args.canvas.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"error: cannot read {args.canvas}: {exc}", file=sys.stderr)
        return 2
    try:
        if args.command == "apply":
            target = apply(document, src=args.src)
            print(f"wrote {target} · {resolve(document, env='engine R')['device'][0]}×"
                  f"{resolve(document, env='engine R')['device'][1]}")
            return 0
        plan = resolve(document, env=f"engine {args.engine.upper()}" if args.engine else "canvas")
    except CanvasError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    if args.engine == "k":
        print(f"engine K · {' '.join(plan['k']) or 'design size (no --scale)'} · {plan['fps']} fps")
    elif args.engine == "r":
        print(f"engine R · {plan['r']['width']}×{plan['r']['height']} · scale {plan['r']['scale']:g} · "
              f"{plan['r']['fps']} fps")
    else:
        print(f"{plan['profile']} · design {plan['design'][0]}×{plan['design'][1]} → device "
              f"{plan['device'][0]}×{plan['device'][1]} · scale {plan['scale']:g} · {plan['fps']} fps · "
              f"K {' '.join(plan['k']) or 'unscaled'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
